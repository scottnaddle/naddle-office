export function authoringText(
  lang: string | null | undefined,
  key: AuthoringStringKey,
  params: Record<string, string | number> = {},
): string {
  const base = (lang ?? 'en').toLowerCase()
  const direct = base as AuthoringLang
  const resolved = STRINGS[direct] ? direct : (base.split('-')[0] as AuthoringLang)
  const text = STRINGS[resolved]?.[key] ?? en[key]
  return text.replace(/\{(\w+)\}/g, (match: string, name: string) =>
    name in params ? String(params[name]) : match,
  )
}
